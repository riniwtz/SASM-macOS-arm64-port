"""SASM's macOS LLDB transport. Runs inside xcrun lldb's Python interpreter.

Newline-delimited JSON on stdin; prefixed JSON events on stdout. Debuggee output
is read separately, so it can never be mistaken for debugger protocol messages.
"""
import json
import codecs
import os
import re
import select
import struct
import tempfile

import lldb


def emit(event, **values):
    payload = ("SASM:" + json.dumps(dict(event=event, **values)) + "\n").encode()
    while payload:
        payload = payload[os.write(1, payload):]


def selected_frame(process):
    thread = process.GetSelectedThread()
    for candidate in process:
        if candidate.GetStopReason() not in (lldb.eStopReasonNone, lldb.eStopReasonInvalid):
            thread = candidate
            process.SetSelectedThread(thread)
            break
    return thread.GetFrameAtIndex(0)


def debug_source_path(target, source):
    # NASM records canonical paths (/private/var/...), while Clang can retain
    # the supplied /var/... spelling. LLDB matches source breakpoints literally.
    canonical = os.path.realpath(source)
    for module_index in range(target.GetNumModules()):
        module = target.GetModuleAtIndex(module_index)
        for unit_index in range(module.GetNumCompileUnits()):
            file = module.GetCompileUnitAtIndex(unit_index).GetFileSpec()
            recorded = os.path.join(file.GetDirectory() or "", file.GetFilename() or "")
            if os.path.realpath(recorded) == canonical:
                return recorded
    return canonical


def watch(target, process, command):
    """Interpret the typed watch requests generated by SASM's memory widget."""
    match = re.fullmatch(r"p(?:/([xtcduf]))? \((int|short|char|long long)(?:\[(\d+)\])?\)\((.*)\)", command)
    # Address watches use *(...) after the type cast instead of (...).
    if not match:
        match = re.fullmatch(r"p(?:/([xtcduf]))? \((int|short|char|long long)(?:\[(\d+)\])?\)\*\(\((?:int|short|char|long long)\*\) \((.*)\)\)", command)
        is_address = True
    else:
        is_address = False
    if not match:
        return None
    fmt, typename, count, expression = match.groups()
    size = {"char": 1, "short": 2, "int": 4, "long long": 8}[typename]
    count = min(int(count or 1), 4096)
    frame = selected_frame(process)
    symbols = target.FindSymbols(expression)
    address = None
    if symbols.GetSize() and not is_address:
        address = symbols.GetContextAtIndex(0).GetSymbol().GetStartAddress().GetLoadAddress(target)
    else:
        value = frame.EvaluateExpression(expression)
        if not value.IsValid() or value.GetError().Fail():
            return None
        if is_address:
            address = value.GetValueAsUnsigned()
        else:
            raw = value.GetValueAsUnsigned() & ((1 << (size * 8)) - 1)
            data = raw.to_bytes(size, "little")
    if address is not None:
        error = lldb.SBError()
        data = process.ReadMemory(address, size * count, error)
        if error.Fail():
            return None
    values = []
    for index in range(0, len(data), size):
        part = data[index:index + size]
        unsigned = int.from_bytes(part, "little")
        signed = int.from_bytes(part, "little", signed=True)
        if fmt == "x": result = hex(unsigned)
        elif fmt == "t": result = bin(unsigned)[2:]
        elif fmt == "u": result = str(unsigned)
        elif fmt == "c": result = repr(chr(unsigned & 255))
        elif fmt == "f" and size in (4, 8): result = str(struct.unpack("<f" if size == 4 else "<d", part)[0])
        else: result = str(signed)
        values.append(result)
    return values[0] if count == 1 else "{" + ", ".join(values) + "}"


def run(debugger, executable, directory, input_file, source):
    debugger.SetAsync(True)
    process = None
    output_dir = tempfile.TemporaryDirectory(prefix="lldb-output-", dir=os.path.dirname(source))
    streams = []
    try:
        target = debugger.CreateTarget(executable)
        if not target.IsValid():
            raise RuntimeError("LLDB could not load the executable.")
        breakpoint_source = debug_source_path(target, source)
        # Break at the first instruction, without skipping a function prologue.
        symbols = target.FindSymbols("main")
        if not symbols.GetSize():
            symbols = target.FindSymbols("_main")
        if not symbols.GetSize():
            raise RuntimeError("Entry point main/_main was not found.")
        entry = target.BreakpointCreateBySBAddress(symbols.GetContextAtIndex(0).GetSymbol().GetStartAddress())
        entry.SetOneShot(True)
        launch = lldb.SBLaunchInfo([])
        launch.SetWorkingDirectory(directory)
        launch.AddOpenFileAction(0, input_file, True, False)
        # LLDB's command interpreter otherwise consumes inferior output before
        # SBProcess.GetSTDOUT can read it. Keep program I/O out of the protocol.
        for descriptor in (1, 2):
            path = os.path.join(output_dir.name, str(descriptor))
            with open(path, "wb"):
                pass
            streams.append((open(path, "rb"), codecs.getincrementaldecoder("utf-8")("replace")))
            launch.AddOpenFileAction(descriptor, path, False, True)
        launch.SetLaunchFlags(launch.GetLaunchFlags() & ~lldb.eLaunchFlagDisableASLR)
        error = lldb.SBError()
        process = target.Launch(launch, error)
        if error.Fail():
            raise RuntimeError("LLDB launch failed: " + str(error))
        pending = b""
        last_stop = -1
        breakpoints = {}
        while True:
            for stream, decoder in streams:
                output = decoder.decode(stream.read())
                if output:
                    emit("output", text=output)
            state = process.GetState()
            if state == lldb.eStateExited:
                for stream, decoder in streams:
                    output = decoder.decode(stream.read(), final=True)
                    if output:
                        emit("output", text=output)
                emit("exited", code=process.GetExitStatus())
                return
            if state in (lldb.eStateCrashed, lldb.eStateStopped, lldb.eStateSuspended):
                stop_id = process.GetStopID()
                if stop_id != last_stop:
                    last_stop = stop_id
                    frame = selected_frame(process)
                    line_entry = frame.GetLineEntry()
                    line = line_entry.GetLine() if line_entry.IsValid() else -2
                    if line_entry.IsValid() and line_entry.GetFileSpec().GetFilename() != os.path.basename(source):
                        line = -2
                    emit("stopped", line=line, pid=process.GetProcessID())
                    if state == lldb.eStateCrashed:
                        emit("error", text="Program stopped after a crash: " + frame.GetThread().GetStopDescription(512))
            if not select.select([0], [], [], 0.05)[0]:
                continue
            chunk = os.read(0, 65536)
            if not chunk:
                return
            pending += chunk
            while b"\n" in pending:
                raw, pending = pending.split(b"\n", 1)
                request = json.loads(raw)
                command = request.get("command")
                if command == "quit":
                    return
                if command == "pause":
                    process.Stop()
                elif command in ("continue", "step", "next"):
                    emit("running")
                    if command == "continue":
                        error = process.Continue()
                        if error.Fail():
                            emit("error", text=str(error))
                    else:
                        selected_frame(process).GetThread().StepInstruction(command == "next")
                elif command == "breakpoint":
                    line = request["line"]
                    if request["added"] and line not in breakpoints:
                        bp = target.BreakpointCreateByLocation(breakpoint_source, line)
                        breakpoints[line] = bp.GetID()
                        if not bp.GetNumLocations():
                            emit("error", text="No executable instruction found for source line " + str(line))
                    elif not request["added"] and line in breakpoints:
                        target.BreakpointDelete(breakpoints.pop(line))
                elif command == "registers":
                    registers = selected_frame(process).GetRegisters()
                    values = []
                    groups = range(registers.GetSize()) if "all-registers" in request.get("text", "") else range(min(1, registers.GetSize()))
                    for index in groups:
                        for register in registers.GetValueAtIndex(index):
                            values.append(dict(name=register.GetName(), hex=register.GetValue() or "",
                                               decimal=str(register.GetValueAsSigned())))
                    emit("registers", values=values)
                elif command == "memory":
                    value = watch(target, process, request["text"])
                    emit("memory", valid=value is not None, value=value or "")
                elif command == "command":
                    text = request.get("text", "")
                    if text.startswith("p "):
                        text = "expression -- " + text[2:]
                    result = lldb.SBCommandReturnObject()
                    debugger.GetCommandInterpreter().HandleCommand(text, result)
                    emit("log" if result.Succeeded() else "error", text=(result.GetOutput() or "") + (result.GetError() or ""))
    except Exception as error:
        emit("error", text=str(error))
        emit("finished")
    finally:
        if process and process.IsValid() and process.GetState() != lldb.eStateExited:
            process.Kill()
        for stream, _ in streams:
            stream.close()
        output_dir.cleanup()
